function f([double]$v) { return $v.ToString("0.##", $inv) }
function v3([double]$x, [double]$y, [double]$z) { return "(" + (f $x) + "," + (f $y) + "," + (f $z) + ")" }
function rad([double]$deg) { return $deg * [Math]::PI / 180.0 }
function polar([double]$r, [double]$deg) { $a = rad $deg; return @(($r * [Math]::Sin($a)), ($r * [Math]::Cos($a))) }
# one baked copy of a mesh-only part at (x,y,z) facing yaw (row count=1 -> baked into the set's Scatter mesh)
function one([string]$kit, [double]$x, [double]$y, [double]$z, [double]$yaw = 0, [double]$scale = 1) {
	$p = v3 $x $y $z
	$L.Add("row $kit  from=$p to=$p count=1 yaw=$(f $yaw) scale=$(f $scale)")
}
function onep([string]$kit, [double]$r, [double]$deg, [double]$y, [double]$yawOff = 0, [double]$scale = 1) {
	$q = polar $r $deg
	one $kit $q[0] $y $q[1] ($deg + $yawOff) $scale
}
function c([string]$t) { $L.Add(""); $L.Add("# $t") }

